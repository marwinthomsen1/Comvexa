export function StudioIcon({ name, size = 19, ...props }) {
  const Component = icons[name] || Settings2;
  return (
    <Component
      size={size}
      fill={name==="starFilled"?"currentColor":"none"}
      strokeWidth={1.75}
      aria-hidden="true"
      focusable="false"
      {...props}
    />
  );
}
export function ToolButton({ icon, children, ...props }) {
  return (
    <button {...props}>
      <StudioIcon name={icon} />
      {children}
    </button>
  );
}
