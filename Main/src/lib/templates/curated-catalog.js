// Normalized coordinates use a 1000-unit width. Each composition explicitly positions
// text, panels, photographs and original editable geometric artwork.
// T: text, R: rectangle, E: ellipse, P: original photograph. Palette slots: b background,
// i ink, a accent, s secondary, w white. Serif/sans/mono are licensed system font stacks.
const T = (
  value,
  x,
  y,
  w,
  h,
  size = 60,
  font = "sans",
  color = "i",
  align = "left",
  weight = "bold",
) => ["t", value, x, y, w, h, size, font, color, align, weight];
const R = (x, y, w, h, color = "a", radius = 0) => [
  "r",
  x,
  y,
  w,
  h,
  color,
  radius,
];
const E = (x, y, w, h, color = "a") => ["e", x, y, w, h, color];
const P = (photo, x, y, w, h, focalY = 0.5) => ["p", photo, x, y, w, h, focalY];
function entry(
  id,
  name,
  category,
  ratio,
  style,
  palette,
  commands,
  description,
) {
  return {
    id: `studio-${id}`,
    name,
    category,
    ratio,
    style,
    palette,
    commands,
    description:
      description ||
      `${name}: an original ${style.toLowerCase()} composition with editable text, colors and artwork.`,
    version: 1,
  };
}
