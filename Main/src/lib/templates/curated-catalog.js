export function getCuratedTemplate(id) {
  const t = curatedTemplates.find((t) => t.id === id);
  if (!t) throw new Error("Template not found.");
  return t;
}
export function filterCuratedTemplates({
  query = "",
  category = "All",
  ratio = "All",
  style = "All",
} = {}) {
  const q = query.trim().toLowerCase();
  return curatedTemplates.filter(
    (t) =>
      (category === "All" || t.category === category) &&
      (ratio === "All" || t.ratio === ratio) &&
      (style === "All" || t.style === style) &&
      `${t.name} ${t.description} ${t.style} ${CURATED_CATEGORIES.find((c) => c[0] === t.category)?.[1]} ${t.commands
        .filter((c) => c[0] === "t")
        .map((c) => c[1])
        .join(" ")}`
        .toLowerCase()
        .includes(q),
  );
}
